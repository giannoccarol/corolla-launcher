BRAND_SCALE = 0.8
SVG_NS = "{http://www.w3.org/2000/svg}"


def paths_of(svg: Path) -> list[str]:
    """Path data of every visible path in [svg]; Material files carry an invisible bounding box."""
    tree = ET.parse(svg)
    if tree.getroot().get("viewBox", "0 0 24 24") != "0 0 24 24":
        raise SystemExit(f"{svg}: expected a 24x24 viewBox")
    result = []
    for path in tree.iter(f"{SVG_NS}path"):
        if path.get("fill") == "none":
            continue
        data = path.get("d", "").strip()
        if data:
            result.append(re.sub(r"\s+", " ", data))
    if not result:
        raise SystemExit(f"{svg}: no path")
    return result


def vector(paths: list[str], scale: float, source: str) -> str:
    body = "\n".join(
        f'        <path\n            android:fillColor="#FFFFFFFF"\n            android:pathData="{d}" />'
        for d in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/import_glyphs.py from {source}. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <group
        android:pivotX="12"
        android:pivotY="12"
        android:scaleX="{scale}"
        android:scaleY="{scale}">
{body}
    </group>
</vector>
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--simple-icons", type=Path, required=True, help="unpacked simple-icons package")
    parser.add_argument("--material", type=Path, required=True, help="unpacked @material-design-icons/svg package")
    args = parser.parse_args()

    for old in DRAWABLE.glob("glyph_*.xml"):
        old.unlink()
    for name, slug in BRANDS.items():
        svg = args.simple_icons / "icons" / f"{slug}.svg"
        source = f"Simple Icons \"{slug}\" (CC0 1.0)"
        (DRAWABLE / f"glyph_{name}.xml").write_text(vector(paths_of(svg), BRAND_SCALE, source))
    for name, icon in SYMBOLS.items():
        svg = args.material / "filled" / f"{icon}.svg"
        source = f"Material Icons \"{icon}\" (Apache License 2.0)"
        (DRAWABLE / f"glyph_{name}.xml").write_text(vector(paths_of(svg), 1.0, source))
    print(f"{len(BRANDS)} brand glyphs and {len(SYMBOLS)} symbols written to {DRAWABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
